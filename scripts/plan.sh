#!/usr/bin/env bash
# Manage the unit plan in book-plan/plan.tsv.
#
#   scripts/plan.sh init             (re)build plan.tsv and chapters/contents.tex
#                                    from chapters-instructions/*.md, keeping the
#                                    status of units that already exist
#   scripts/plan.sh list             print the plan
#   scripts/plan.sh next             print the id of the first unit not done
#                                    (nothing when all are done)
#   scripts/plan.sh get <id> <field> field: status | target | spec | exercises | order
#   scripts/plan.sh set <id> <status> status: todo | in_progress | done | blocked
#   scripts/plan.sh prompt <id>      print the chapter-writer prompt for a unit
#
# Spec files are named NN-<id>.md (NN gives the order). Optional header lines
# anywhere in the first 15 lines of a spec:
#   Target: <path.tex>     default chapters/<id>.tex
#   Exercises: no          default yes (lint requires three exercise levels)
#   Contents: no           default yes for targets under chapters/ (whether the
#                          target is \input from chapters/contents.tex)
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

PLAN="book-plan/plan.tsv"
SPECS="chapters-instructions"
CONTENTS="chapters/contents.tex"
HEADER=$'order\tid\tstatus\ttarget\tspec\texercises\tcontents'

die() { echo "plan.sh: $*" >&2; exit 1; }

need_plan() { [[ -f "$PLAN" ]] || die "$PLAN missing; run scripts/plan.sh init"; }

header_value() { # <spec> <key> -> value or empty
  head -n 15 "$1" | sed -n "s/^$2:[[:space:]]*//Ip" | head -n 1 | tr -d '\r' | sed 's/[[:space:]]*$//'
}

field_index() {
  case "$1" in
    order) echo 1 ;; id) echo 2 ;; status) echo 3 ;; target) echo 4 ;;
    spec) echo 5 ;; exercises) echo 6 ;; contents) echo 7 ;;
    *) die "unknown field '$1'" ;;
  esac
}

row() { # <id> -> plan row
  need_plan
  awk -F'\t' -v id="$1" 'NR>1 && $2==id {print; found=1} END {exit !found}' "$PLAN" \
    || die "unknown unit '$1'"
}

cmd_init() {
  shopt -s nullglob
  local specs=("$SPECS"/[0-9]*-*.md)
  ((${#specs[@]})) || die "no specs found in $SPECS/ (expected NN-<id>.md)"

  declare -A old_status=()
  if [[ -f "$PLAN" ]]; then
    while IFS=$'\t' read -r _ id status _; do
      [[ "$id" == id ]] && continue
      old_status["$id"]="$status"
    done < "$PLAN"
  fi

  local tmp; tmp="$(mktemp)"
  echo "$HEADER" > "$tmp"
  declare -A seen=()
  local f base order id target exercises contents status
  for f in $(printf '%s\n' "${specs[@]}" | sort -V); do
    base="$(basename "$f" .md)"
    order="${base%%-*}"
    id="${base#*-}"
    [[ -n "$id" && "$id" != "$base" ]] || die "bad spec name '$f'"
    [[ -z "${seen[$id]:-}" ]] || die "duplicate unit id '$id'"
    seen["$id"]=1
    target="$(header_value "$f" Target)"; target="${target:-chapters/$id.tex}"
    exercises="$(header_value "$f" Exercises | tr 'A-Z' 'a-z')"; exercises="${exercises:-yes}"
    contents="$(header_value "$f" Contents | tr 'A-Z' 'a-z')"
    if [[ -z "$contents" ]]; then
      [[ "$target" == chapters/* ]] && contents=yes || contents=no
    fi
    status="${old_status[$id]:-todo}"
    printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$order" "$id" "$status" "$target" "$f" "$exercises" "$contents" >> "$tmp"
  done
  mkdir -p "$(dirname "$PLAN")"
  mv "$tmp" "$PLAN"

  mkdir -p "$(dirname "$CONTENTS")"
  {
    echo "% Generated by scripts/plan.sh init from $SPECS/. Do not edit."
    echo "% Each unit is optional so the book compiles before it is written."
    awk -F'\t' 'NR>1 && $7=="yes" {t=$4; sub(/\.tex$/, "", t); printf "\\InputIfFileExists{%s}{}{}\n", t}' "$PLAN"
  } > "$CONTENTS"

  echo "plan: $(($(wc -l < "$PLAN") - 1)) units written to $PLAN; contents in $CONTENTS"
}

cmd_list() {
  need_plan
  column -t -s $'\t' "$PLAN"
}

cmd_next() {
  need_plan
  awk -F'\t' 'NR>1 && $3!="done" {print $2; exit}' "$PLAN"
}

cmd_get() {
  [[ $# -eq 2 ]] || die "usage: get <id> <field>"
  local i; i="$(field_index "$2")"
  row "$1" | cut -f "$i"
}

cmd_set() {
  [[ $# -eq 2 ]] || die "usage: set <id> <status>"
  case "$2" in todo|in_progress|done|blocked) ;; *) die "bad status '$2'" ;; esac
  row "$1" > /dev/null
  local tmp; tmp="$(mktemp)"
  awk -F'\t' -v OFS='\t' -v id="$1" -v st="$2" 'NR>1 && $2==id {$3=st} {print}' "$PLAN" > "$tmp"
  mv "$tmp" "$PLAN"
  echo "$1 -> $2"
}

cmd_prompt() {
  [[ $# -eq 1 ]] || die "usage: prompt <id>"
  local r spec target exercises prev
  r="$(row "$1")"
  spec="$(cut -f5 <<<"$r")"; target="$(cut -f4 <<<"$r")"; exercises="$(cut -f6 <<<"$r")"
  prev="$(awk -F'\t' -v id="$1" 'NR>1 {if ($2==id) {print p; exit}; p=$2}' "$PLAN")"
  local lint="scripts/lint-unit.sh $1"
  cat <<EOF
Write one unit of the book in this repository.

UNIT: $1
SPEC: $spec
TARGET FILE: $target
PREVIOUS UNIT: ${prev:-none}
EXERCISES REQUIRED: $exercises

Follow your agent instructions (reading order, writing, verify, continuity
record, final report). Verify with \`scripts/build.sh\` and \`$lint\`.
EOF
}

case "${1:-}" in
  init)   shift; cmd_init "$@" ;;
  list)   shift; cmd_list "$@" ;;
  next)   shift; cmd_next "$@" ;;
  get)    shift; cmd_get "$@" ;;
  set)    shift; cmd_set "$@" ;;
  prompt) shift; cmd_prompt "$@" ;;
  *) sed -n '2,20p' "$0" | sed 's/^# \{0,1\}//'; exit 1 ;;
esac
